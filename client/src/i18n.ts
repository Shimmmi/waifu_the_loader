export type TKey = keyof typeof ru;
const dicts = { ru: ru as Dict, en };

export function ruPlural(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

export function translate(lang: 'ru' | 'en', key: TKey, vars?: Record<string, string | number>): string {
  const s = dicts[lang][key] ?? ru[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => String(vars[k] ?? m)) : s;
}

export function useT(): (key: TKey, vars?: Record<string, string | number>) => string {
  const lang = useStore((s) => s.settings.lang);
  return (key, vars) => translate(lang, key, vars);
}
