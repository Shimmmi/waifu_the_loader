import { describe, expect, it } from 'vitest';
import { censor } from './censor.js';

describe('Маскировка мата', () => {
  it('маскирует и короткие, и длинные формы, не трогая обычные слова', () => {
    expect(censor('Ёб твою мать, это же экзистенция')).toBe('Ё* твою мать, это же экзистенция');
    expect(censor('Ну что, бля, поехали')).toBe('Ну что, б*я, поехали');
    expect(censor('Взяли, нахрен!')).toBe('Взяли, н****н!');
    expect(censor('Похер, что лифт сломан')).toBe('П***р, что лифт сломан');
    expect(censor('охуеть')).toBe('о****ь');
    expect(censor('Хребет, хлеб, сейф, ребёнок не при чём')).toBe('Хребет, хлеб, сейф, ребёнок не при чём');
  });
});
