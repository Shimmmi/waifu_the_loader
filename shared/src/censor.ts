/** Маскировка мата для режима «без мата» (уровень 0): «хрен» → «х**н». */
const PREFIX = '(?:за|по|на|у|от|вы|до|раз|рас|при|о|об|подъ|съ|въ|изъ|пере|недо|ни|наи)?';
const ROOTS = [
  'бля', 'хуй', 'хуе', 'хуё', 'хуя', 'хуи', 'хер', 'хрен', 'пизд', 'еба', 'ебл', 'ебу', 'ебн', 'ебись', 'ёб',
  'сука', 'суки', 'сучк', 'сран', 'срат', 'сру', 'жоп', 'залуп', 'мудак', 'мудил', 'дерьм', 'говн', 'долбо', 'охрен', 'охуе',
];

const re = new RegExp(`(?<!\\p{L})(${PREFIX}(?:${ROOTS.join('|')})\\p{L}*)`, 'giu');

export function censor(text: string): string {
  return text.replace(re, (w) => (w.length <= 2 ? w : w[0] + '*'.repeat(w.length - 2) + w[w.length - 1]));
}
